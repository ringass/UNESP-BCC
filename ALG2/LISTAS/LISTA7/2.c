#include <stdio.h>
#include <string.h>
#include <stdlib.h>
#include <ctype.h>
#include <math.h>

void Sort(int *v, int len)
{
    

    for (int j = 0; j < len-1; j++)
    {
        int menor = j;

        for (int i = j+1; i < len; i++)
        {
            if (v[i] < v[menor])
            {
                menor = i;

            }
        }

        if(menor != j){
            int aux = v[j];
            v[j] = v[menor];
            v[menor] = aux;

        }
    }
}

    int main()
    {

        int v[10] = {7, 9, 5, 4, 10, 15, 25, 90, 1, 32};
        
        Sort(v, 10);

        for(int i = 0; i < 10; i++){
            printf("%d ", v[i]);
        }

        return 0;
    }
